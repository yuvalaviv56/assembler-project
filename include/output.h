/*
 * output.h
 * פונקציות אשר תפקידן ליצור את קבצי הפלט של האסמבלר
 * 
 * קובץ זה מגדיר את הפונקציות שיוצרות את שלושת סוגי קבצי הפלט
 * שהאסמבלר מייצר בסוף התהליך
 * 
 * קובץ ob - מכיל את כל הקוד והנתונים המקודדים
 * קובץ ent - entry-מכיל רשימת סמלים שהוגדרו כ
 * קובץ ext - מכיל רשימת כתובות שבהן השתמשנו בסמלים חיצוניים
 */

#ifndef OUTPUT_H
#define OUTPUT_H

#include "structures.h"
#include "globals.h"

/*
 * פונ' אשר יוצרת את קובץ האובייקט
 * 
 * קובץ זה מכיל את כל תוכן הזיכרון המקודד
 * השורה הראשונה מציינת מספר מילות קוד ומספר מילות נתונים יש
 * לאחר מכן כלל המילים מוצגות עם כתובתן בפורמט הקסדצימלי
 * 
 * פרמטרים:
 *   base_name - שם הקובץ ללא סיומת
 *   memory - מצביע למבנה הזיכרון שמכיל את כלל הקוד והנתונים
 * 
 * מחזירה: TRUE אם הצליח ליצור את הקובץ 
 *          FALSE אם נכשל*/
bool create_object_file(const char *base_name, MemoryImage *memory);

/*
 * entry-פונ' אשר יוצרת את קובץ ה
 * 
 * entry-הקובץ מכיל רשימה של כל הסמלים שהוגדרו כ
 * כל שורה מכילה שם סמל ואת הכתובת שלו
 *הפונ' לא יוצרת קובץ entry אם אין סמלי   
 * 
 * פרמטרים:
 *   base_name - שם הקובץ ללא סיומת
 *   symbols - מצביע לטבלת הסמלים
 * 
 * מחזירה: TRUE אם הצליח ליצור את הקובץ 
 *          FALSE אם נכשל*/
bool create_entries_file(const char *base_name, SymbolTable *symbols);

/*
 * externals-יוצרת את קובץ ה
 * 
 * הקובץ מכיל רשימה של כל המקומות שבהם השתמשנו בסמלים חיצוניים
 * כל שורה מכילה שם סמל חיצוני ואת הכתובת שבה השתמשנו בו
 * אם אין הפניות לסמלים חיצוניים הפונקציה לא יוצרת קובץ
 * 
 * פרמטרים:
 *   base_name - שם הקובץ ללא סיומת
 *   externals - מצביע לרשימת ההפניות החיצוניות
 * 
 * מחזירה: TRUE אם הצליח ליצור את הקובץ 
 *          FALSE אם נכשל*/
bool create_externals_file(const char *base_name, ExternalList *externals);

#endif
